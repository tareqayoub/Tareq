export function translate(lang, key, vars = {}) {
  const parts = key.split('.')
  let node = dict[lang]
  for (const p of parts) {
    node = node?.[p]
    if (node === undefined) return key
  }
  if (typeof node !== 'string') return key
  return node.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`))
}
